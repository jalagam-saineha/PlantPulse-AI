from app.extensions import db
from app.models.user import utcnow


class TimelineEvent(db.Model):
    """
    A point-in-time health/growth record for a plant, derived from an
    Analysis or a VideoFrame, used to render the Health Timeline.
    """
    __tablename__ = "timeline_events"

    id = db.Column(db.Integer, primary_key=True)
    plant_id = db.Column(db.Integer, db.ForeignKey("plants.id"), nullable=False, index=True)

    source_type = db.Column(db.String(20), nullable=False)  # 'analysis' | 'video_frame'
    source_id = db.Column(db.Integer, nullable=False)

    event_date = db.Column(db.DateTime, nullable=False, index=True)
    image_path = db.Column(db.String(255), nullable=True)
    health_score = db.Column(db.Float, nullable=True)
    leaf_area_px = db.Column(db.Integer, nullable=True)
    yellowing = db.Column(db.Float, nullable=True)
    damage = db.Column(db.Float, nullable=True)
    notes = db.Column(db.Text, nullable=True)

    created_at = db.Column(db.DateTime, nullable=False, default=utcnow)

    def __repr__(self):
        return f"<TimelineEvent plant={self.plant_id} date={self.event_date}>"


class Report(db.Model):
    """A generated PDF report tied to a plant / analysis."""
    __tablename__ = "reports"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False, index=True)
    plant_id = db.Column(db.Integer, db.ForeignKey("plants.id"), nullable=False, index=True)
    analysis_id = db.Column(db.Integer, db.ForeignKey("analyses.id"), nullable=True, index=True)

    file_path = db.Column(db.String(255), nullable=False)
    title = db.Column(db.String(200), nullable=False, default="PlantPulse AI Report")

    created_at = db.Column(db.DateTime, nullable=False, default=utcnow)

    plant = db.relationship("Plant", backref=db.backref("reports", lazy="dynamic", cascade="all, delete-orphan"))

    def __repr__(self):
        return f"<Report id={self.id} plant={self.plant_id}>"


class Notification(db.Model):
    """An in-app notification generated by a real system event."""
    __tablename__ = "notifications"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False, index=True)

    title = db.Column(db.String(160), nullable=False)
    message = db.Column(db.String(400), nullable=False)
    is_read = db.Column(db.Boolean, nullable=False, default=False)
    link = db.Column(db.String(255), nullable=True)

    created_at = db.Column(db.DateTime, nullable=False, default=utcnow, index=True)

    def __repr__(self):
        return f"<Notification {self.title!r} read={self.is_read}>"
